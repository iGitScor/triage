#!/usr/bin/env python3
"""Keeps Remora on the Estuary design system's tokens (@iscor/design, pinned in package.json).

Two files are made from the package, and checked to be up to date:

- site/public/site/tokens.css, the package's dist/tokens.css as is (the site is static: no bundler to import it);
- macos/Sources/Remora/Presentation/MynaTokens.swift, every colour in the four appearances (light, dark, and both
  under Increase Contrast) and the disabled opacity, from the package's tokens.json. Theme.swift (`Myna`) builds on it.

After updating the package (`npm install --save-exact @iscor/design@x.y.z`, here, in desktop/app and in docs), run
`python3 scripts/tokens-check.py --write`. The Windows app and the docs import the package's CSS themselves.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "node_modules/@iscor/design"
SITE = ROOT / "site/public/site/tokens.css"
SWIFT = ROOT / "macos/Sources/Remora/Presentation/MynaTokens.swift"

if not PACKAGE.exists():
    sys.exit("@iscor/design isn't installed: run `npm ci` at the repository's root.")

version = json.loads((PACKAGE / "package.json").read_text())["version"]
tokens = json.loads((PACKAGE / "dist/tokens.json").read_text())


def camel(name: str) -> str:
    """ink-soft → inkSoft, card-2 → card2, as the package's Swift names."""
    return re.sub(r"-(\w)", lambda m: m.group(1).upper(), name)


def hex_and_alpha(value: str) -> tuple[str, str]:
    """#rrggbb or #rrggbbaa → ("0xRRGGBB", alpha as Swift writes it)."""
    alpha = round(int(value[7:9], 16) / 255, 2) if len(value) == 9 else 1
    return f"0x{value[1:7].upper()}", f"{alpha:g}"


def colour(name: str) -> str:
    light, light_alpha = hex_and_alpha(tokens["light"][name])
    dark, dark_alpha = hex_and_alpha(tokens["dark"][name])
    contrast_light, contrast_light_alpha = hex_and_alpha(tokens["contrast"]["light"][name])
    contrast_dark, contrast_dark_alpha = hex_and_alpha(tokens["contrast"]["dark"][name])
    return (
        f"    static let {camel(name)} = Color(\n"
        f"        light: {light}, dark: {dark}, lightOpacity: {light_alpha}, darkOpacity: {dark_alpha},\n"
        f"        contrast: ({contrast_light}, {contrast_dark}), contrastOpacity: ({contrast_light_alpha}, {contrast_dark_alpha}))"
    )


swift = f"""// Generated by `python3 scripts/tokens-check.py --write` from @iscor/design {version}: don't edit, update the package.
import SwiftUI

/// The Estuary design system's colours, in light and dark, with and without Increase Contrast.
extension Myna {{
{chr(10).join(colour(name) for name in tokens["light"])}

    /// A control that can't be used yet: dimmed to this, the same in both schemes.
    static let disabledOpacity = {tokens["base"]["disabled"]:g}
}}
"""

made = {SITE: (PACKAGE / "dist/tokens.css").read_text(), SWIFT: swift}
if "--write" in sys.argv:
    for path, text in made.items():
        path.write_text(text)
stale = [path.relative_to(ROOT) for path, text in made.items() if not path.exists() or path.read_text() != text]
if stale:
    sys.exit(
        f"Not made from @iscor/design {version}: {', '.join(map(str, stale))}. Run `python3 scripts/tokens-check.py --write`."
    )
print(f"✓ the site's tokens.css and the Mac's MynaTokens.swift are made from @iscor/design {version}")
